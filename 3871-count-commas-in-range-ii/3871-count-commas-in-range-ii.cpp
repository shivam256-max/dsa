class Solution {
public:
    long long countCommas(long long n) {
        if(n<1000){
            return 0;
        }
        long long ans=0;
       
        if(n<1000000){
            ans=(n-1000)+1;
        }
        else{
            if(n<1000000000LL){
                ans=((n-1000000+1)*2)+999000;




            }
            else{
                if(n<1000000000000LL){
                    ans=((n-1000000000LL+1)*3)+((1000000000LL-1000000)*2)+999000;
                }
                else{
                    if(n<1000000000000000LL){
                        ans=ans+((n-1000000000000LL+1)*4)+((1000000000000LL-1000000000LL)*3)+((1000000000LL-1000000LL)*2)+999000;
                    }
                    else{
                        ans=((1000000000000000LL-1000000000000LL)*4)+((1000000000000LL-1000000000LL)*3)+((1000000000LL-1000000LL)*2)+999000+(n-1000000000000000LL+1)*5 ;
                    }
                }
            }
        }
        return ans;
        
    }
};